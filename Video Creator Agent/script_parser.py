def parse_script(path):
    """Parse script file (.docx or .txt) and return structured spoken sections."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"ফাইল পাওয়া যায়নি: {path}")

    ext = os.path.splitext(path)[1].lower()
    if ext == ".docx":
        sections = parse_script_docx(path)
    elif ext in (".txt", ".md"):
        sections = parse_script_txt(path)
    else:
        raise ValueError(f"অসমর্থিত ফাইল ফরম্যাট: {ext} (শুধু .docx অথবা .txt সমর্থিত)")

    date_label = extract_date(path)

    # Sanitize any accidental "নমস্কার" into "আসসালামু আলাইকুম"
    for s in sections:
        if s.get("text"):
            s["text"] = re.sub(r"^(?:নমস্কার\s*(?:বন্ধুরা)?|নমস্কার!)\s*", "আসসালামু আলাইকুম। ", s["text"]).strip()
            s["text"] = re.sub(r"নমস্কার\s*(?:বন্ধুরা)?", "আসসালামু আলাইকুম", s["text"]).strip()

    return date_label, sections
