"""
Script Parser for Video Creator Agent.
Parses script .docx or .txt generated by Writer Agent / Voice Over Agent.
"""

import os
import re
from datetime import datetime, timedelta, timezone

from docx import Document

DATE_PAT = re.compile(r"\d{4}-\d{2}-\d{2}")
# টাইটেলের ভিতরে "---" থাকলেও পুরো টাইটেল রাখা হয় — শেষ ড্যাশ-রান শুধু মুছে যায়।
# আগে (.*?)\s*---+ ছিল: মাঝে --- থাকলে লেজি ম্যাচ প্রথম ড্যাশ-রানে থেমে যেত।
NEWS_HEADER_PAT = re.compile(r"^---+\s*খবর\s*(\d{1,3}):\s*(.+?)\s*(?:-{2,})?\s*$")
INTRO_PAT = re.compile(r"^===+\s*INTRO\s*===+", re.IGNORECASE)
OUTRO_PAT = re.compile(r"^===+\s*OUTRO(?:\s*/\s*CTA)?\s*===+", re.IGNORECASE)

# বাংলাদেশ সময় (UTC+6) — undated ফাইলে fallback তারিখ ঢাকা সময়েই হয়
DHAKA_TZ = timezone(timedelta(hours=6))

SKIP_PREFIXES = (
    "লক্ষ্য সময়:",
    "শব্দ:",
    "উৎস:",
    "তৈরি:",
    "সংবাদ:",
    "ভয়েস-ওভার স্ক্রিপ্ট",
)


def _clean(text):
    return re.sub(r"\s+", " ", (text or "")).strip()


def extract_date(path):
    match = DATE_PAT.search(os.path.basename(path))
    if match:
        return match.group(0)
    return datetime.now(DHAKA_TZ).strftime("%Y-%m-%d")


def find_latest_script(base_dir, writer_dir=None):
    """Find the most recent script docx or txt in Voice Over Agent or Writer Agent."""
    candidates = []
    search_dirs = [base_dir]
    if writer_dir and os.path.isdir(writer_dir):
        search_dirs.append(writer_dir)
        search_dirs.append(os.path.join(writer_dir, "output"))

    for folder in search_dirs:
        if not os.path.isdir(folder):
            continue
        for root, _dirs, files in os.walk(folder):
            if "__pycache__" in root or ".system_generated" in root:
                continue
            for name in files:
                if name.startswith("~$"):
                    continue
                lower = name.lower()
                if (lower.endswith(".docx") or lower.endswith(".txt")) and "script_" in lower:
                    candidates.append(os.path.join(root, name))

    if not candidates:
        return ""
    # ফাইলের নামের তারিখ (script_YYYY-MM-DD) প্রাধান্য পায় — OneDrive sync/restore
    # পুরোনো ফাইলের mtime নাড়ালেও ভুল স্ক্রিপ্ট নির্বাচিত হবে না। mtime টাই-ব্রেকার।
    def _name_date(p):
        m = DATE_PAT.search(os.path.basename(p))
        return m.group(0) if m else ""

    candidates.sort(key=lambda p: (_name_date(p), os.path.getmtime(p)), reverse=True)
    return candidates[0]


def parse_script_docx(path):
    document = Document(path)
    sections = []
    current = None

    for para in document.paragraphs:
        text = _clean(para.text)
        if not text:
            continue

        # Check section headers
        if INTRO_PAT.match(text):
            if current and current.get("text"):
                sections.append(current)
            current = {
                "kind": "intro",
                "number": 0,
                "title": "ইন্ট্রো",
                "filename_prefix": "00_intro",
                "text": "",
            }
            continue

        match_news = NEWS_HEADER_PAT.match(text)
        if match_news:
            if current and current.get("text"):
                sections.append(current)
            num = int(match_news.group(1))
            title = _clean(match_news.group(2))
            current = {
                "kind": "news",
                "number": num,
                "title": title,
                "filename_prefix": f"{num:02d}_news_{num:02d}",
                "text": "",
            }
            continue

        if OUTRO_PAT.match(text):
            if current and current.get("text"):
                sections.append(current)
            current = {
                "kind": "outro",
                "number": 99,
                "title": "আউট্রো",
                "filename_prefix": "99_outro",
                "text": "",
            }
            continue

        # Skip metadata and document headings
        if any(text.startswith(prefix) for prefix in SKIP_PREFIXES):
            continue
        if "Gemini AI দিয়ে রূপান্তরিত" in text or "শুভ ভয়েস-ওভার" in text:
            continue

        # Body text of current section
        if current is not None:
            if current["text"]:
                current["text"] += " " + text
            else:
                current["text"] = text

    if current and current.get("text"):
        sections.append(current)

    return sections


